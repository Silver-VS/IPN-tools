// Contratos de investigación sin navegador ni red; solo datos ficticios en memoria.
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const c=vm.createContext({TextEncoder,Response,Blob,CompressionStream,DecompressionStream,Uint8Array,btoa,atob});
vm.runInContext(readFileSync('web/sate/guia.js','utf8'),c);
const G=c.SateGuia,plain=x=>JSON.parse(JSON.stringify(x));
const docs={z:{titulo:'Reglamento General de Estudios',articulos:[{n:'48',texto:'Artículo íntegro. II. Obligación específica.',fracciones:[{fr:'II',texto:'Obligación específica.'}]},{n:'9',texto:'Plazo para solicitar.'}]},a:{titulo:'Otro reglamento',articulos:[{n:'1',texto:'Texto literal & % $ # _ { } ~ ^ \\.'}]}};
const cita=(doc,n,fr='',nota='',tipo='personal')=>({doc,n,fr,inciso:'',nota,tipo,huella:'',anotaciones:[]});
const p={formato:'sate-investigacion',version:2,nombre:'Prueba & % $ # _ { } ~ ^ \\',autor:'',proposito:'estudio',etiquetas:[],peticion:'Petición ficticia',marcadores:[cita('z','48','II','Mi decisión','hecho'),cita('a','1'),cita('z','9','','No incorporar') ]};
p.marcadores[0].anotaciones.push({inicio:0,fin:5,literal:'Texto',nota:'Anotación previa',etiqueta:'favor'});
const url=await G.enlaceInvestigacion(p,'https://example.invalid/sate/#/ficticia/guia/reglamentos/z','#/ficticia/guia/investigacion');
assert.ok(url.startsWith('https://example.invalid/sate/#/ficticia/guia/investigacion?inv='));
assert.deepEqual(plain(await G.decodificarInv(new URLSearchParams(url.split('?')[1]).get('inv'))),plain(G.validarInvestigacion(p)));
assert.deepEqual(plain(G.filtrarCitasInv(p,docs,'DECISION','hecho')).map(m=>m.n),['48']);
for(const q of ['OBLIGACION ESPECIFICA','articulo integro','ANOTACION PREVIA'])assert.equal(G.filtrarCitasInv(p,docs,q).length,1);
assert.equal(G.filtrarCitasInv(p,docs,'decisión','personal').length,0);
assert.equal(G.filtrarCitasInv(p,docs,'').length,3);
const etiqueta=(k,v={})=>({referencia:'Artículo '+v.n,referencia_fraccion:'fracción '+v.fr,inciso:'inciso '+v.inciso,propia:'Tu nota',no_disponible:'No disponible'}[k]||k);
const fundamento=G.copiarFundamentoInv(p.marcadores,docs,etiqueta);
assert.ok(fundamento.indexOf('Otro reglamento')<fundamento.indexOf('Reglamento General de Estudios'));
assert.ok(fundamento.indexOf('Artículo 9,')<fundamento.indexOf('Artículo 48,'));
assert.equal(fundamento.split('\n\nReglamento General de Estudios\n\n').length,2);
assert.ok(fundamento.includes('Obligación específica.\n(Artículo 48, fracción II, Reglamento General de Estudios)'));
assert.ok(!fundamento.includes('Mi decisión')&&!fundamento.includes('No incorporar')&&!fundamento.includes('Anotación previa'));
assert.ok(G.copiarFundamentoInv(p.marcadores,docs,etiqueta,true).includes('Tu nota: Mi decisión\nAnotación previa'));
const filtradas=G.filtrarCitasInv(p,docs,'obligacion','hecho');
assert.ok(!G.copiarFundamentoInv(filtradas,docs,etiqueta).includes('Artículo 9,'));
const tex=await G.exportarLatexInv(p,async doc=>docs[doc],etiqueta);
assert.match(tex,/^\\documentclass\{article\}/);assert.ok(tex.includes('\\usepackage[spanish]{babel}'));
assert.equal((tex.match(/\\begin\{quote\}/g)||[]).length,3);
assert.equal((tex.match(/\\end\{quote\}/g)||[]).length,3);
assert.ok(tex.includes('\\end{quote}\n\nTu nota: Mi decisión'));
assert.ok(tex.includes('Artículo 48, fracción II, Reglamento General de Estudios'));
assert.equal(G.escaparLatexInv('& % $ # _ { } ~ ^ \\'),'\\& \\% \\$ \\# \\_ \\{ \\} \\textasciitilde{} \\textasciicircum{} \\textbackslash{}');
assert.ok(tex.endsWith('\\end{document}\n'));
assert.deepEqual(p.marcadores.map(m=>m.n),['48','1','9'],'exportar no cambia el orden personal');
