import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const json=p=>JSON.parse(readFileSync(p,'utf8'));
const datos=json('web/dist/sate/datos/upiita/electivas.json');
const fuente=readFileSync('web/sate/electivas.js','utf8');
const textos=readFileSync('contenido/textos/es.toml','utf8');
const reglas=vm.createContext({});
vm.runInContext(readFileSync('tests/fixtures/ventanilla/electivas-calculo.js','utf8')+';globalThis.credOf=credOf',reglas);
const c=vm.createContext({console,ElectivasReglas:{},SATE_CONFIG:{},SATE:{texto:k=>k},SateTramites:{registrar(){}},document:{},window:{},localStorage:{getItem(){return null}}});
vm.runInContext(fuente,c);
const filas=(unidad,car,plan,claves)=>claves.map(clave=>{
  const row=datos.mapas[unidad].rows.find(r=>r[0]===car&&r[1]===plan&&r[3]===clave);
  assert.ok(row,`Existe ${unidad} ${car}/${plan}/${clave}`);return row;
});
const seleccion=[...filas('upiita','B','09',['B101','B102','B103']),...filas('escom','A','20',['A101','A102'])];
const actividades=seleccion.map(row=>c.SateElectivas.actividadMapa(row===seleccion[3]||row===seleccion[4]?'escom':'upiita',row[0],row[1],row));
const ids=actividades.map(a=>c.SateElectivas.origenId({unidad:a.origen.unidad,car:a.origen.carrera,plan:a.origen.plan,clave:a.origen.clave}));
assert.equal(new Set(ids).size,5,'Cada materia conserva un origen único');
assert.equal(actividades.length,5,'No se agrega dos veces una selección');
assert.deepEqual(actividades.map(a=>[+a.ht,+a.hp]),seleccion.map(r=>[+r[7],+r[8]]));
const calculados=actividades.reduce((s,a)=>s+reglas.credOf(a),0);
const formula=actividades.reduce((s,a)=>s+Math.floor(((+a.ht + +a.hp)*18/16)*100)/100,0);
assert.equal(calculados,formula,'Los créditos usan la fórmula vigente de R.credOf');
const perfil=json('data/perfiles-prueba/cambio-carrera-mecatronica.json');
assert.equal(perfil.perfil_prueba.id,'cambio-carrera-mecatronica');
const clavesActuales=new Set(datos.mapas.upiita.rows.filter(r=>r[0]==='M').map(r=>r[3]));
assert.ok(perfil.acreditadas.some(r=>clavesActuales.has(r[0])&&r[3]==='EQV'),'El perfil contiene equivalencias que no deben sugerirse');
const candidatas=acreditadas=>acreditadas.filter(r=>r&&!clavesActuales.has(r[0])&&Object.values(datos.mapas).some(m=>m.rows.some(x=>x[3]===r[0])));
assert.deepEqual(candidatas(perfil.acreditadas),[],'El perfil cambio de carrera no recibe sugerencias de su kárdex');
const claveExterna=Object.values(datos.mapas).flatMap(m=>m.rows.map(r=>r[3])).find(k=>!clavesActuales.has(k));
assert.ok(claveExterna&&candidatas([[claveExterna,8,'25/1','ORD']]).length===1,'Un perfil ficticio con materia acreditada de otro plan sí recibe sugerencia');
assert.match(fuente,/const car=carrera\(\)\|\|a\.carrera,plan=identidad\(\)\?\.plan\|\|a\.plan;/,'Sin carrera confirmada se usa la del SAES para excluir el plan actual');
assert.match(fuente,/const materias=\(a\.acreditadas\|\|\[\]\)\.filter\(r=>r&&!actuales\.has\(r\[0\]\)\)/,'Solo se consideran materias acreditadas ajenas al plan actual');
assert.match(fuente,/if\(sugeridas\.length\)/,'No aparece la sección de kárdex si no hay sugerencias');
assert.match(fuente,/x\.unidad\.toUpperCase\(\)/,'Los botones usan siglas');
for(const k of ['cc_buscar_placeholder','cc_elige_carrera','cc_elige_plan','cc_elige_unidad','cc_ya_agregada','cc_resumen','cc_semestre','cc_materia','cc_carrera_fallback'])assert.match(textos,new RegExp('^'+k+'\\s*=', 'm'),`Texto ${k} en es.toml`);
assert.doesNotMatch(fuente,/placeholder='Clave o nombre'|'Elige una carrera'|'Elige un plan'|'Elige unidad académica'|\(ya agregada\)|teóricas \+/,'Los textos fijos viven en es.toml');
assert.doesNotMatch(fuente,/ctxDatos/,'Los datos se pasan desde ctx.datos');
assert.match(fuente,/nodo\('details'\)/,'El selector es plegable');
assert.match(fuente,/row\[2\]/,'La lista se agrupa por semestre');
console.log('OK cambio de carrera: equivalencias excluidas, kárdex condicional, siglas y textos centralizados');
